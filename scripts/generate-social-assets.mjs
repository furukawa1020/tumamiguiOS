import { chromium } from "playwright";
import { spawn } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import http from "node:http";
import { setTimeout as wait } from "node:timers/promises";

const PROJECT_ROOT = process.cwd();
const OUT_PATH = path.join(PROJECT_ROOT, "public", "og-image.png");
const PREVIEW_URL = "http://127.0.0.1:4173/?mode=pointer";
const PREVIEW_PORT = "4173";

const waitForServer = async (timeoutMs = 15000) => {
  const startAt = Date.now();
  while (Date.now() - startAt < timeoutMs) {
    try {
      await new Promise((resolve, reject) => {
        const req = http.get("http://127.0.0.1:4173", (res) => {
          res.resume();
          resolve(void 0);
        });
        req.on("error", reject);
      });
      return;
    } catch {
      await wait(500);
    }
  }
  throw new Error("Failed to boot local preview for OGP screenshot");
};

const runCommand = (command, args, timeoutMs = 120000) =>
  new Promise((resolve, reject) => {
    const proc = spawn(command, args, { cwd: PROJECT_ROOT, stdio: "inherit" });
    const timer = setTimeout(() => {
      proc.kill("SIGKILL");
      reject(new Error(`Command timed out: ${command} ${args.join(" ")}`));
    }, timeoutMs);

    proc.on("error", (error) => {
      clearTimeout(timer);
      reject(error);
    });
    proc.on("close", (code) => {
      clearTimeout(timer);
      if (code === 0) {
        resolve();
      } else {
        reject(new Error(`Command failed: ${command} ${args.join(" ")} (code: ${code})`));
      }
    });
  });

const ensurePlaywrightBrowser = async () => {
  await runCommand(process.platform === "win32" ? "npx.cmd" : "npx", [
    "playwright",
    "install",
    "chromium",
  ]);
};

const run = async () => {
  const server = spawn(
    process.platform === "win32" ? "npm.cmd" : "npm",
    ["run", "dev", "--", "--host", "127.0.0.1", "--port", PREVIEW_PORT, "--strictPort"],
    { cwd: PROJECT_ROOT, stdio: "ignore" },
  );

  const close = () => {
    if (!server.killed) {
      server.kill();
    }
  };

  try {
    await waitForServer();
    let browser;
    try {
      browser = await chromium.launch({ headless: true });
    } catch (error) {
      const message = String(error instanceof Error ? error.message : error);
      if (message.includes("Executable doesn't exist")) {
        await ensurePlaywrightBrowser();
        browser = await chromium.launch({ headless: true });
      } else {
        throw error;
      }
    }
    const context = await browser.newContext({ viewport: { width: 1200, height: 630 } });
    const page = await context.newPage();

    await page.goto(PREVIEW_URL, { waitUntil: "domcontentloaded", timeout: 30000 });
    try {
      await page
        .getByRole("button", { name: "Start pointer mode" })
        .click({ timeout: 4000 });
      await page.waitForSelector("#app-canvas", { timeout: 8000 });
      const canvas = page.locator("#app-canvas");
      await canvas.waitFor({ timeout: 6000 });
      const handle = await canvas.elementHandle();
      if (handle) {
        await handle.screenshot({ path: OUT_PATH, type: "png" });
      } else {
        await page.screenshot({ path: OUT_PATH, type: "png" });
      }
    } catch {
      await page.screenshot({ path: OUT_PATH, type: "png" });
    }

    await browser.close();
  } finally {
    close();
  }

  const stats = fs.statSync(OUT_PATH);
  console.log(`og image generated by screenshot: ${OUT_PATH} (${stats.size} bytes)`);
};

run().catch((error) => {
  console.error(error);
  const message = String(error instanceof Error ? error.message : error);
  const canSkip =
    message.includes("Executable doesn't exist") ||
    message.includes("Browser not found") ||
    message.includes("Could not find browser executable");

  if (canSkip) {
    console.warn("Skipping OGP screenshot generation because browser is unavailable.");
    process.exitCode = 0;
    return;
  }
  process.exitCode = 1;
});
